using Microsoft.EntityFrameworkCore;

namespace Altairis.Api.Data;

/// <summary>
/// Demo reservations over the seeded inventory window (~400k), and then the inventory counters
/// recalculated from them, so BookedRooms always matches real bookings.
/// </summary>
public static class ReservationSeeder
{
    public static async Task SeedAsync(AppDbContext db, CancellationToken ct = default)
    {
        if (await db.Reservations.AnyAsync(ct) || !await db.Availability.AnyAsync(ct))
            return;

        var today = DateOnly.FromDateTime(DateTime.UtcNow);
        var start = InventorySeeder.SeedStart(today);
        var days = InventorySeeder.SeedDays;

        // Same reason as the inventory seed: hundreds of thousands of rows are generated by SQL Server
        // in one statement. How stays are built without ever overbooking:
        //
        //  - Each room's allotment (TotalRooms) is split into "blocks" of 1-2 rooms.
        //  - Each block is booked as a back-to-back sequence of stays: a stay starts every P days
        //    and lasts L nights (L <= P), so stays inside a block never overlap. Blocks are disjoint,
        //    so the sum of booked rooms on any night can never exceed TotalRooms.
        //  - L/P is the occupancy. It depends on the hotel's popularity (35-90%), and stays further
        //    in the future are randomly dropped (fewer bookings made yet: the booking pace).
        //  - Status follows the dates: past stays checked out (a few no-shows), current ones checked in,
        //    today's arrivals half checked in, future ones confirmed (and ~4% cancelled).
        //  - Prices are the sum of each night's price (override or base) x rooms, as in a real booking.
        //  - CHECKSUM(...) gives stable pseudo-random numbers, so every machine gets the same data.
        db.Database.SetCommandTimeout(TimeSpan.FromMinutes(5));
        await db.Database.ExecuteSqlAsync($"""
            WITH Nums AS (
                SELECT TOP (64) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) - 1 AS N FROM sys.all_objects
            ),
            Allotment AS (
                SELECT a.RoomId, MAX(a.TotalRooms) AS T FROM Availability a GROUP BY a.RoomId
            ),
            Blocks AS (
                SELECT al.RoomId, r.HotelId, rt.Capacity, b.N AS B,
                       CASE WHEN al.T - 2 * b.N >= 2 THEN 2 ELSE 1 END AS BlockRooms,
                       3 + ABS(CHECKSUM(al.RoomId, b.N)) % 5 AS P,                 -- period 3..7 days
                       35 + ABS(CHECKSUM(r.HotelId, 17)) % 56 AS OccPct,           -- hotel popularity
                       ABS(CHECKSUM(al.RoomId, b.N, 99)) % 7 AS Offset
                FROM Allotment al
                JOIN Rooms r ON r.Id = al.RoomId
                JOIN RoomTypes rt ON rt.Id = r.RoomTypeId
                JOIN Nums b ON b.N < (al.T + 1) / 2
            ),
            Stays AS (
                SELECT bl.*, d.N AS StartIdx,
                       CASE WHEN (bl.P * bl.OccPct + 50) / 100 < 1 THEN 1 ELSE (bl.P * bl.OccPct + 50) / 100 END AS L,
                       ABS(CHECKSUM(bl.RoomId, bl.B, d.N)) % 100 AS H
                FROM Blocks bl
                JOIN Nums d ON d.N < {days} AND (d.N + bl.Offset) % bl.P = 0
            ),
            Dated AS (
                SELECT s.*,
                       DATEADD(day, s.StartIdx, {start}) AS CheckIn,
                       -- clip stays at the end of the inventory window
                       DATEADD(day, CASE WHEN s.StartIdx + s.L > {days} THEN {days} ELSE s.StartIdx + s.L END, {start}) AS CheckOut
                FROM Stays s
                -- booking pace: the further ahead, the more stays haven't been booked yet
                WHERE s.StartIdx - {InventorySeeder.PastDays} <= 0
                   OR s.H >= (s.StartIdx - {InventorySeeder.PastDays}) * 5 / 2
            )
            INSERT INTO Reservations (RoomId, CheckIn, CheckOut, Rooms, Guests, GuestName, GuestEmail,
                                      TotalPrice, Status, CreatedAt, CreatedBy, CancelledAt)
            SELECT x.RoomId, x.CheckIn, x.CheckOut, x.BlockRooms,
                   1 + ABS(CHECKSUM(x.RoomId, x.B, x.StartIdx, 5)) % (x.Capacity * x.BlockRooms),
                   x.FirstName + ' ' + x.LastName,
                   LOWER(x.FirstName + '.' + x.LastName) + '@example.com',
                   x.BlockRooms * (SELECT SUM(COALESCE(av.Price, rm.BasePrice))
                                   FROM Availability av JOIN Rooms rm ON rm.Id = av.RoomId
                                   WHERE av.RoomId = x.RoomId AND av.[Date] >= x.CheckIn AND av.[Date] < x.CheckOut),
                   x.Status,
                   x.CreatedAt,
                   'seed',
                   CASE WHEN x.Status = 'Cancelled'
                        THEN DATEADD(minute, DATEDIFF(minute, x.CreatedAt, SYSUTCDATETIME()) * (x.H % 90 + 5) / 100, x.CreatedAt)
                   END
            FROM (
                SELECT dt.*,
                       CHOOSE(1 + ABS(CHECKSUM(dt.RoomId, dt.StartIdx, 1)) % 20,
                           'Maria', 'Jose', 'Lucia', 'Carlos', 'Ana', 'David', 'Laura', 'Javier', 'Sofia', 'Pablo',
                           'Elena', 'Miguel', 'Carmen', 'Daniel', 'Paula', 'Sergio', 'Marta', 'Alejandro', 'Julia', 'Andres') AS FirstName,
                       CHOOSE(1 + ABS(CHECKSUM(dt.RoomId, dt.StartIdx, 2)) % 20,
                           'Garcia', 'Martinez', 'Lopez', 'Sanchez', 'Perez', 'Gomez', 'Fernandez', 'Ruiz', 'Diaz', 'Moreno',
                           'Alvarez', 'Romero', 'Navarro', 'Torres', 'Dominguez', 'Vazquez', 'Ramos', 'Gil', 'Serrano', 'Molina') AS LastName,
                       CASE
                           WHEN ABS(CHECKSUM(dt.RoomId, dt.B, dt.StartIdx, 7)) % 100 < 4 AND dt.CheckIn > {today} THEN 'Cancelled'
                           WHEN dt.CheckOut < {today} THEN CASE WHEN dt.H % 50 = 0 THEN 'NoShow' ELSE 'CheckedOut' END
                           WHEN dt.CheckOut = {today} THEN CASE WHEN dt.H % 2 = 0 THEN 'CheckedOut' ELSE 'CheckedIn' END
                           WHEN dt.CheckIn < {today} THEN 'CheckedIn'
                           WHEN dt.CheckIn = {today} THEN CASE WHEN dt.H % 5 < 2 THEN 'CheckedIn' ELSE 'Confirmed' END
                           ELSE 'Confirmed'
                       END AS Status,
                       -- Future stays were booked during the last 30 days; past ones 1-45 days before arrival.
                       CASE WHEN dt.CheckIn > {today}
                            THEN DATEADD(minute, -(ABS(CHECKSUM(dt.RoomId, dt.StartIdx, 3)) % 43200), SYSUTCDATETIME())
                            ELSE DATEADD(minute, -(1440 + ABS(CHECKSUM(dt.RoomId, dt.StartIdx, 3)) % 63360), CAST(dt.CheckIn AS datetime2))
                       END AS CreatedAt
                FROM Dated dt
            ) x;
            """, ct);

        await RecalculateBookedRoomsAsync(db, ct);
        db.Database.SetCommandTimeout(null);
    }

    /// <summary>
    /// Rebuilds every Availability.BookedRooms from the reservations that hold rooms
    /// (everything except Cancelled). Used after the seed; it's also the repair tool if the
    /// counter ever drifted (e.g. after a manual fix in the database).
    /// </summary>
    public static Task RecalculateBookedRoomsAsync(AppDbContext db, CancellationToken ct = default) =>
        db.Database.ExecuteSqlAsync($"""
            UPDATE a
            SET BookedRooms = ISNULL(b.Booked, 0)
            FROM Availability a
            LEFT JOIN (
                SELECT av.Id, SUM(r.Rooms) AS Booked
                FROM Reservations r
                JOIN Availability av ON av.RoomId = r.RoomId AND av.[Date] >= r.CheckIn AND av.[Date] < r.CheckOut
                WHERE r.Status <> 'Cancelled'
                GROUP BY av.Id
            ) b ON b.Id = a.Id;
            """, ct);
}
